let beliefIndex = 0;

/*************************
 * BELIEF SECTION ✅
 *************************/
const openBelief = () => {
  cardArea.innerHTML = `
    <div class="question-card">
      <div class="question-text">🧠 اصلاح باورها</div>

      ${programSubBtn("📖 چرا باورهایمان را اصلاح کنیم؟", "openWhyBelief", "#8360c3,#2ebf91")}
      ${programSubBtn("🧠 باورساز", "startBeliefCards", "#ff7a18,#ffb347")}

      <button onclick="startProgram()" style="${backBtnStyle()}">
        ⬅ بازگشت
      </button>
    </div>
  `;
};

function openWhyBelief() {
  cardArea.innerHTML = `
    <div class="question-card">
      <div class="question-text">📖 چرا باورهایمان را اصلاح کنیم؟</div>
      <p style="margin-top:12px; line-height:1.9">
        باورها فیلتر نگاه ما به زندگی هستند.
        با اصلاح باورهای محدودکننده، مسیر رشد،
        آرامش و پیشرفت هموارتر می‌شود.
      </p>
      <button onclick="openBelief()" style="${backBtnStyle()}">
        ⬅ بازگشت
      </button>
    </div>
  `;
}

function startBeliefCards() {
  beliefIndex = 0;
  renderBeliefCard();
}

function renderBeliefCard() {
  cardArea.innerHTML = `
    <div class="question-card">
      <div class="question-number">
        باور ${beliefIndex + 1} از ${BELIEF_LIST.length}
      </div>

      <div class="question-text" style="margin-top:14px; line-height:2">
        ${BELIEF_LIST[beliefIndex]}
      </div>

      <button onclick="nextBelief()" style="${mainBtnStyle()}">
        💪 من می‌تونم
      </button>

      <button onclick="prevBelief()" style="${backBtnStyle()}">
        ⬅ قبلی
      </button>

      <button onclick="startProgram()" style="${backBtnStyle()}">
        🏠 منوی اصلی
      </button>
    </div>
  `;
}

function nextBelief() {
  if (beliefIndex < BELIEF_LIST.length - 1) {
    beliefIndex++;
    renderBeliefCard();
  }
}

function prevBelief() {
  if (beliefIndex > 0) {
    beliefIndex--;
    renderBeliefCard();
  }
}
